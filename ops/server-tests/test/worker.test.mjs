import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { runHead } from '../worker.mjs';

test('an exact candidate runs once on the server and publishes a git result consumed by CI', async t => {
  const root = await mkdtemp(join(tmpdir(), 'server-tests-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const repository = join(root, 'source');
  await mkdir(join(repository, 'scripts'), { recursive: true });
  const git = (...args) => execFileSync('git', args, { cwd: repository, encoding: 'utf8' }).trim();
  git('init', '-b', 'main');
  git('config', 'user.name', 'Test');
  git('config', 'user.email', 'test@example.invalid');
  await writeFile(join(repository, 'scripts/test-owners.mjs'), `import {appendFileSync} from 'node:fs';
if(process.argv[2]==='--run')appendFileSync(process.env.TEST_MARKER,'ran\\n');
console.log('server test passed');\n`);
  await writeFile(join(repository, 'scripts/julia-agents.mjs'), `import{spawnSync}from'node:child_process';const r=spawnSync(process.argv[3],process.argv.slice(4),{stdio:'inherit'});process.exit(r.status??1);\n`);
  git('add', '.');
  git('commit', '-m', 'candidate');
  const sha = git('rev-parse', 'HEAD');
  const marker = join(root, 'executions');
  const env = { ...process.env, TEST_MARKER: marker };
  const config = { repository, state: join(root, 'state') };
  const first = await runHead(config, sha, { env });
  assert.equal(first.exitCode, 0);
  const second = await runHead(config, sha, { env });
  assert.equal(second.head, sha);
  assert.equal(await readFile(marker, 'utf8'), 'ran\n');
  assert.equal(JSON.parse(git('show', `refs/notes/julia-server-tests/${sha}:result.json`)).head, sha);
  const output = execFileSync(process.execPath, [new URL('../../../scripts/await-server-tests.mjs', import.meta.url).pathname, sha, '--remote', repository, '--timeout', '2'], { cwd: root, encoding: 'utf8' });
  assert.match(output, /Server tests passed/);
  git('remote', 'add', 'origin', repository);
  const defaultRemote = execFileSync(process.execPath, [new URL('../../../scripts/await-server-tests.mjs', import.meta.url).pathname, sha, '--timeout', '2'], { cwd: repository, encoding: 'utf8' });
  assert.match(defaultRemote, /Server tests passed/);
  await writeFile(join(repository, 'scripts/test-owners.mjs'), `if(process.argv[2]==='--run'){console.error('server assertion failed');process.exit(1);}\n`);
  git('add', '.'); git('commit', '-m', 'failing candidate');
  const failedHead = git('rev-parse', 'HEAD');
  assert.equal((await runHead(config, failedHead, { env })).exitCode, 1);
  assert.throws(() => execFileSync(process.execPath, [new URL('../../../scripts/await-server-tests.mjs', import.meta.url).pathname, failedHead, '--remote', repository, '--timeout', '2'], { cwd: root, encoding: 'utf8', stdio: 'pipe' }), /Server tests failed/);
});

test('a dead claim without a result is recovered and does not starve the next candidate', async t => {
  const root = await mkdtemp(join(tmpdir(), 'server-tests-recovery-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const repository = join(root, 'source');
  await mkdir(join(repository, 'scripts'), { recursive: true });
  const git = (...args) => execFileSync('git', args, { cwd: repository, encoding: 'utf8' }).trim();
  git('init', '-b', 'main'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  await writeFile(join(repository, 'scripts/test-owners.mjs'), `console.log('server tests executed');\n`);
  await writeFile(join(repository, 'scripts/julia-agents.mjs'), `import{spawnSync}from'node:child_process';process.exit(spawnSync(process.argv[3],process.argv.slice(4),{stdio:'inherit'}).status??1);\n`);
  git('add', '.'); git('commit', '-m', 'candidate');
  const sha = git('rev-parse', 'HEAD');
  const state = join(root, 'state');
  await mkdir(join(state, sha), { recursive: true });
  const result = await runHead({ repository, state }, sha);
  assert.equal(result.exitCode, 0);
  assert.equal(JSON.parse(git('show', `refs/notes/julia-server-tests/${sha}:result.json`)).exitCode, 0);
});
