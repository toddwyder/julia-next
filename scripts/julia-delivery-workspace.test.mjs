import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { git, redProof } from './julia-minimal-runner-checks.mjs';
import { seamsOf } from './julia-delivery-workspace.mjs';

// Verbatim from JUL-208 as read from Linear on 13 Oct 2026. The surrounding
// card is intentionally represented too: the parser must find the agreed
// behavior list in a real to-spec description, not a purpose-built heading.
const JUL_208_CARD_TEXT = `> *This was generated by AI during triage.*

# Keep a private recipe

## Acceptance criteria

- [ ] Front door is the logo and one Google button.
- [ ] Build test-first at the observable seams below.

## Test seams and regression selection

* Rejected UI sign-in plus raw reads/writes: catches an interface-only access restriction.
* Supplied and omitted numeric facts: catches invented yield/time or invalid arithmetic inputs.
* Double Save and retry: catches duplicate creation with a new ID.
* Observer during multi-record Save: catches partial version visibility.
* Cancel, view and search readback: catches unintended writes or Recent updates.
* Other accepted account readback: catches incorrect household scoping.

Cross each affected interface above and runtime row with actual intended services. Controlled fault adapters may support deterministic failure handling, never replace real connection/account proof. Preserve the mandatory gate contracts when moving redundant checks out of the ten-minute gate. Select changed journeys by impact; no permanent all-journey browser suite.

## Runtime dependency matrix

These are required boundaries with explicit unresolved identities, not a qualified runtime plan.`;

test('the real JUL-208 to-spec behavior list selects changed tests for before-and-after proof', () => {
  assert.deepEqual(seamsOf(JUL_208_CARD_TEXT), {
    kind: 'behavior',
    tests: null,
    behaviors: [
      'Rejected UI sign-in plus raw reads/writes: catches an interface-only access restriction.',
      'Supplied and omitted numeric facts: catches invented yield/time or invalid arithmetic inputs.',
      'Double Save and retry: catches duplicate creation with a new ID.',
      'Observer during multi-record Save: catches partial version visibility.',
      'Cancel, view and search readback: catches unintended writes or Recent updates.',
      'Other accepted account readback: catches incorrect household scoping.',
    ],
  });
});

test('to-spec behavior seams still require their changed tests to fail before and pass after', async t => {
  const worktree = await mkdtemp(join(tmpdir(), 'to-spec-red-proof-'));
  t.after(() => rm(worktree, { recursive: true, force: true }));
  git(worktree, 'init', '-q');
  await writeFile(join(worktree, 'behavior.mjs'), 'export const enabled = false;\n');
  git(worktree, 'add', '.');
  git(worktree, '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-q', '-m', 'start');
  const base = git(worktree, 'rev-parse', 'HEAD');
  git(worktree, 'checkout', '-q', '-b', 'candidate');
  await writeFile(join(worktree, 'behavior.mjs'), 'export const enabled = true;\n');
  await writeFile(join(worktree, 'behavior.test.mjs'), 'checks enabled behavior\n');
  git(worktree, 'add', '.');
  git(worktree, '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-q', '-m', 'candidate');
  const sha = git(worktree, 'rev-parse', 'HEAD');
  const runs = [];
  const reason = await redProof({
    worktree, branch: 'candidate', base, sha,
    seams: seamsOf(JUL_208_CARD_TEXT),
    test: async request => {
      runs.push({ files: request.files, source: await readFile(join(worktree, 'behavior.mjs'), 'utf8') });
      return { status: (await readFile(join(worktree, 'behavior.mjs'), 'utf8')).includes('true') ? 0 : 1, output: '' };
    },
  });
  assert.equal(reason, null);
  assert.deepEqual(runs.map(run => run.files), [['behavior.test.mjs'], ['behavior.test.mjs']]);
  assert.match(runs[0].source, /true/);
  assert.match(runs[1].source, /false/);
});
