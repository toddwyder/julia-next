#!/usr/bin/env node
// The programs that begin a card and carry its stages, listed in one readable
// place: docs/agents/machine-programs.md.
//
//   node scripts/machine-programs.mjs --write   rewrite the list
//   node scripts/machine-programs.mjs --check   fail while the list is stale
//
// A pull request that changes one of these programs updates the list in the
// same pull request. The check compares each listed program's fingerprint with
// the one written down, so a change that leaves the list behind fails instead
// of shipping quietly. A program under machine/flow that the list does not
// name fails too, so a new piece cannot join the machine unseen.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const repoRoot = resolve(here, '..');

export const LIST_FILE = 'docs/agents/machine-programs.md';

const FIX = 'run `node scripts/machine-programs.mjs --write` and commit the list with the change';

export const PROGRAMS = [
  ['src/mastra/index.ts', 'The Studio entry. Registers the card workflow so the run form can start a card.'],
  ['machine/flow/workflow.mjs', 'The order of the stages, the loops and the one place a card waits.'],
  ['machine/flow/steps.mjs', 'What each stage does, including the build being a real agent step.'],
  ['machine/flow/agents.mjs', 'The agents the stages run, and what the build agent may touch.'],
  ['machine/flow/exploration.mjs', 'The gate routing raw grep and glob workspace and shell commands to Graphify.'],
  ['machine/flow/graphify.mjs', 'The Graphify graph tools Lead and its helpers query before reading files.'],
  ['machine/flow/models.mjs', 'The Lead model, read from its independent setting and routed through its account provider.'],
  ['machine/flow/role-models.mjs', 'The Lead helper models, read from the saved role table and routed to account providers.'],
  ['machine/flow/schema.mjs', 'What the run form asks for and what the run remembers.'],
  ['machine/flow/scratch.mjs', 'The run folder: artifacts, verdicts and the report a stop leaves.'],
  ['machine/flow/spending.mjs', 'The per-card spending ledger, its dollar limit and the processor that counts each model call.'],
  ['machine/flow/card-ledger.mjs', 'Reads and writes the spending ledger file for one card.'],
  ['machine/flow/mastra.mjs', 'Storage and tracing, so a run is written down and priced.'],
  ['machine/flow/start.mjs', 'Assembles a run to read it back and to resume a card.'],
  ['machine/flow/run.mjs', 'Answers a waiting card, reads a run, writes its cost. No way to start one.'],
  ['machine/flow/trace.mjs', 'Turns the trace file into the run cost record.'],
  ['scripts/julia-agents.mjs', 'Runs a machine command with the Julia keys it needs.'],
].map(([path, what]) => ({ path, what }));

// Every plain program in the workflow folder belongs on the list, so a piece
// added later is either named here or caught by the check.
export function flowPrograms(root = repoRoot) {
  const dir = join(root, 'machine/flow');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter(name => name.endsWith('.mjs') && !name.endsWith('.test.mjs'))
    .sort()
    .map(name => `machine/flow/${name}`);
}

export function fingerprint(root, path) {
  return createHash('sha256').update(readFileSync(join(root, path))).digest('hex');
}

export function renderList(root = repoRoot) {
  const rows = PROGRAMS.map(({ path, what }) => `| \`${path}\` | ${what} | \`${fingerprint(root, path)}\` |`);
  return [
    '# Machine programs',
    '',
    '<!-- Generated by `node scripts/machine-programs.mjs --write`. Do not edit by hand. -->',
    '',
    'These are the programs that begin a card and carry its stages. A pull request that changes one of',
    'them updates this list in the same pull request, and `node scripts/machine-programs.mjs --check`',
    'fails while the list is stale. The fingerprint is the file\'s sha256, so the check catches a change',
    'of any size, not only a change to the sentence beside it.',
    '',
    '| Program | What it does | sha256 |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

const LISTED = /^\|\s*`([^`]+)`\s*\|[^|]*\|\s*`([0-9a-f]{64})`\s*\|$/;

export function listedEntries(text) {
  return [...text.matchAll(new RegExp(LISTED.source, 'gm'))].map(match => ({
    path: match[1],
    fingerprint: match[2],
  }));
}

export function checkPrograms(root = repoRoot) {
  const file = join(root, LIST_FILE);
  if (!existsSync(file)) return [`${LIST_FILE}: missing; ${FIX}`];

  const entries = listedEntries(readFileSync(file, 'utf8'));
  const failures = [];
  const seen = new Set();

  for (const { path, fingerprint: written } of entries) {
    seen.add(path);
    if (!existsSync(join(root, path))) {
      failures.push(`${LIST_FILE}: lists ${path}, which no longer exists; ${FIX}`);
    } else if (fingerprint(root, path) !== written) {
      failures.push(`${LIST_FILE}: ${path} changed since the list was written; ${FIX}`);
    }
  }

  for (const { path } of PROGRAMS) {
    if (!seen.has(path)) failures.push(`${LIST_FILE}: never names ${path}; ${FIX}`);
  }
  for (const path of flowPrograms(root)) {
    if (!seen.has(path)) failures.push(`${LIST_FILE}: never names ${path}; ${FIX}`);
  }

  return failures;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(process.argv[3] ?? '.');
  const mode = process.argv[2] ?? '--check';
  if (mode === '--write') {
    writeFileSync(join(root, LIST_FILE), renderList(root));
    console.log(`Wrote ${LIST_FILE}.`);
  } else if (mode === '--check') {
    const failures = checkPrograms(root);
    if (failures.length) {
      console.error(failures.join('\n'));
      process.exitCode = 1;
    } else console.log('The machine program list matches the programs.');
  } else {
    console.error('usage: node scripts/machine-programs.mjs [--write|--check] [root]');
    process.exitCode = 2;
  }
}
